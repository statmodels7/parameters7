# The AR(1) log-determinant, its derivatives and the inverse are evaluated from
# the free value z = atanh(rho), because rho itself rounds to -1 or 1 from
# |z| of about 19, where 1 - rho^2 computed from rho loses every digit.

# mpmath references (60 digits) at eta = (0, z): q(z) = (p-1) log(1 - rho^2)
# and its first four derivatives in z, and the entries [1, 1] and [1, 2] of the
# inverse at scale 1.
ar1_ref <- function() {
  data.frame(
    p = rep(c(2, 4, 10), each = 5),
    z = rep(c(-40, -20, 0.7, 20, 40), 3),
    ld0 = c(-78.613705638880109, -38.613705638880109, -0.45454045871701118, -38.613705638880109, -78.613705638880109, -235.84111691664033, -115.84111691664033, -1.3636213761510335, -115.84111691664033, -235.84111691664033, -707.52335074992098, -347.52335074992098, -4.0908641284531006, -347.52335074992098, -707.52335074992098),
    ld1 = c(2.0, 2.0, -1.2087355542343269, -2.0, -2.0, 6.0, 5.9999999999999999, -3.6262066627029808, -5.9999999999999999, -6.0, 18.0, 18.0, -10.878619988108942, -18.0, -18.0),
    ld2 = c(-1.4438811102763321e-34, -3.3986834042332712e-17, -1.2694791799649172, -3.3986834042332712e-17, -1.4438811102763321e-34, -4.3316433308289964e-34, -1.0196050212699814e-16, -3.8084375398947517, -1.0196050212699814e-16, -4.3316433308289964e-34, -1.2994929992486989e-33, -3.0588150638099441e-16, -11.425312619684255, -3.0588150638099441e-16, -1.2994929992486989e-33),
    ld3 = c(-2.8877622205526643e-34, -6.7973668084665423e-17, 1.5344646201838331, 6.7973668084665423e-17, 2.8877622205526643e-34, -8.6632866616579928e-34, -2.0392100425399627e-16, 4.6033938605514993, 2.0392100425399627e-16, 8.6632866616579928e-34, -2.5989859984973978e-33, -6.117630127619888e-16, 13.810181581654498, 6.117630127619888e-16, 2.5989859984973978e-33),
    ld4 = c(-5.7755244411053286e-34, -1.3594733616933084e-16, -0.24318455476647275, -1.3594733616933084e-16, -5.7755244411053286e-34, -1.7326573323315986e-33, -4.0784200850799253e-16, -0.72955366429941825, -4.0784200850799253e-16, -1.7326573323315986e-33, -5.1979719969947957e-33, -1.2235260255239776e-15, -2.1886609928982547, -1.2235260255239776e-15, -5.1979719969947957e-33),
    inv11 = rep(c(1.3851555960983775e+34, 58846316709254997.0, 1.5754492326965702, 58846316709254997.0, 1.3851555960983775e+34), 3),
    inv12 = rep(c(1.3851555960983775e+34, 58846316709254996.0, -0.95215075072576693, -58846316709254996.0, -1.3851555960983775e+34), 3)
  )
}

test_that("the AR(1) log-determinant and its derivatives are exact at large free values", {
  ref <- ar1_ref()
  for (i in seq_len(nrow(ref))) {
    s <- ar1(ref$p[i])
    eta <- c(0, ref$z[i])
    got <- c(
      param_logdet(s, eta),
      param_dlogdet(s, eta)[["z_rho"]],
      param_d2logdet(s, eta)[["z_rho:z_rho"]],
      param_d3logdet(s, eta)[["z_rho:z_rho:z_rho"]],
      param_d4logdet(s, eta)[["z_rho:z_rho:z_rho:z_rho"]]
    )
    want <- unlist(ref[i, paste0("ld", 0:4)])
    for (k in 1:5) {
      expect_lt(abs(got[k] - want[k]), 1e-13 * abs(want[k]),
        label = sprintf("order %d at p = %d, z = %g", k - 1, ref$p[i], ref$z[i]))
    }
  }
})

test_that("the AR(1) inverse is exact at large free values", {
  ref <- ar1_ref()
  for (i in seq_len(nrow(ref))) {
    inv <- param_solve(ar1(ref$p[i]), c(0, ref$z[i]))
    expect_lt(abs(inv[1L, 1L] - ref$inv11[i]), 1e-13 * abs(ref$inv11[i]))
    expect_lt(abs(inv[1L, 2L] - ref$inv12[i]), 1e-13 * abs(ref$inv12[i]))
  }
})
